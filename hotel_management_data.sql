-- ==========================================
-- HOTEL MANAGEMENT SYSTEM DATABASE
-- ==========================================

CREATE DATABASE hotel_management;

USE hotel_management;
CREATE TABLE users (user_id varchar(100) PRIMARY KEY,username VARCHAR(50) NOT NULL,password VARCHAR(255) NOT NULL,first_name VARCHAR(100) NOT NULL,last_name VARCHAR(100) NOT NULL,email VARCHAR(100) NOT NULL,phone_number VARCHAR(20),address VARCHAR(255));


CREATE TABLE admins (admin_id varchar(100) PRIMARY KEY,role VARCHAR(50),hire_date DATE,email VARCHAR(100),password VARCHAR(100));


CREATE TABLE room_types (room_type_id varchar(100) PRIMARY KEY,type_name VARCHAR(50),description TEXT);


CREATE TABLE rooms (room_id varchar(100) PRIMARY KEY,room_number VARCHAR(10) NOT NULL,room_type_id varchar(100),floor INT,capacity INT,price_per_night DECIMAL(10, 2),status VARCHAR(20),FOREIGN KEY (room_type_id) REFERENCES room_types(room_type_id));


CREATE TABLE reservations (reservation_id varchar(100) PRIMARY KEY,user_id varchar(100),room_id varchar(100),check_in_date DATE,check_out_date DATE,amount DECIMAL(10, 2),status VARCHAR(20),FOREIGN KEY (user_id) REFERENCES users(user_id),FOREIGN KEY (room_id) REFERENCES rooms(room_id));


CREATE TABLE room_inventory (inventory_id varchar(100) PRIMARY KEY,room_id varchar(100),quantity_available INT,quantity_in_use INT,FOREIGN KEY (room_id) REFERENCES rooms(room_id));



CREATE TABLE departments (department_id varchar(100) PRIMARY KEY,department_name VARCHAR(100));

CREATE TABLE employees (employee_id varchar(100) PRIMARY KEY,user_id varchar(100),department_id varchar(100),position VARCHAR(100),hire_date DATE,FOREIGN KEY (user_id) REFERENCES users(user_id),FOREIGN KEY (department_id) REFERENCES departments(department_id));




CREATE TABLE payments (payment_id varchar(100) PRIMARY KEY,reservation_id varchar(100),amount DECIMAL(10, 2),payment_date DATE,payment_method VARCHAR(50),status VARCHAR(20),FOREIGN KEY (reservation_id) REFERENCES reservations(reservation_id));


CREATE TABLE invoices (invoice_id varchar(100) PRIMARY KEY,reservation_id varchar(100),total_amount DECIMAL(10, 2),issued_date DATE,due_date DATE,FOREIGN KEY (reservation_id) REFERENCES reservations(reservation_id));


CREATE TABLE services (service_id varchar(100) PRIMARY KEY,service_name VARCHAR(100),description TEXT,price DECIMAL(10, 2));


CREATE TABLE housekeeping (housekeeping_id varchar(100) PRIMARY KEY,room_id varchar(100),service_id varchar(100),service_date DATE,FOREIGN KEY (room_id) REFERENCES rooms(room_id),FOREIGN KEY (service_id) REFERENCES services(service_id));


CREATE TABLE feedback (feedback_id varchar(100) PRIMARY KEY,reservation_id varchar(100),rating INT,comments TEXT,feedback_date DATE,FOREIGN KEY (reservation_id) REFERENCES reservations(reservation_id));


CREATE TABLE discounts (discount_id varchar(100) PRIMARY KEY,discount_code VARCHAR(50),description TEXT,discount_percentage DECIMAL(5, 2));


CREATE TABLE hotel_policies (policy_id varchar(100) PRIMARY KEY,policy_name VARCHAR(100),description TEXT);








